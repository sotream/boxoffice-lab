// Metric catalogue extracted from the source (counter(...), gauge(...), histogram(...) calls), plus checks that
// ops/alerts.yml and docs/operations.md agree with it. Used by ops/check.mjs and packages/platform/src/ops-consistency.test.ts.
import { readdirSync, readFileSync, statSync } from "node:fs";
import { createRequire } from "node:module";
import { join, relative } from "node:path";
import { parse } from "yaml";

export const SERVICES = ["gateway", "inventory", "waiting-room", "payments", "catalog", "notifications"];
// Services that have a Postgres pool / an HTTP server instrumented by the platform.
const PG_SERVICES = ["inventory", "payments", "catalog", "notifications"];
const HTTP_SERVICES = ["gateway", "inventory", "waiting-room", "payments", "catalog"];

function* walk(dir) {
  for (const f of readdirSync(dir)) {
    if (f === "node_modules" || f === "dist") continue;
    const p = join(dir, f);
    if (statSync(p).isDirectory()) yield* walk(p);
    else if (p.endsWith(".ts") && !p.endsWith(".test.ts")) yield p;
  }
}

const CALL = /\b(counter|gauge|histogram)\(\s*([A-Za-z_][A-Za-z0-9_]*|"[^"]+")\s*,\s*"((?:[^"\\]|\\.)*)"\s*(?:,\s*\[([^\]]*)\])?/g;

export function scanCatalogue(root) {
  const metrics = new Map();
  const roots = [["platform", join(root, "packages/platform/src")], ...SERVICES.map((s) => [s, join(root, "services", s, "src")])];
  for (const [owner, dir] of roots) {
    for (const file of walk(dir)) {
      const src = readFileSync(file, "utf8");
      const consts = Object.fromEntries([...src.matchAll(/export const ([A-Z_]+)\s*=\s*"([^"]+)"/g)].map((m) => [m[1], m[2]]));
      for (const m of src.matchAll(CALL)) {
        const name = m[2].startsWith('"') ? m[2].slice(1, -1) : consts[m[2]];
        if (!name) throw new Error(`${relative(root, file)}: cannot resolve metric name ${m[2]}`);
        const labels = (m[4] ?? "").split(",").map((x) => x.trim().replace(/"/g, "")).filter(Boolean);
        const services = owner !== "platform" ? [owner] : name.startsWith("http_") ? HTTP_SERVICES : name.startsWith("pg_pool_") ? PG_SERVICES : SERVICES;
        if (metrics.has(name)) throw new Error(`metric ${name} defined twice (${relative(root, file)})`);
        metrics.set(name, { name, type: m[1], help: m[3], labels, services, file: relative(root, file) });
      }
    }
  }
  return [...metrics.values()].sort((a, b) => a.name.localeCompare(b.name));
}

/** Names of the Node/process metrics prom-client registers by default, taken from the installed prom-client. */
export function defaultMetricNames(root) {
  const req = createRequire(join(root, "packages/platform/package.json"));
  const prom = req("prom-client");
  const reg = new prom.Registry();
  prom.collectDefaultMetrics({ register: reg });
  return reg.getMetricsAsArray().map((m) => m.name);
}

export const TABLE_START = "<!-- metrics:start (generated by `node ops/check.mjs --write`) -->";
export const TABLE_END = "<!-- metrics:end -->";

export function renderTable(cat) {
  const all = (s) => (s.length === SERVICES.length ? "all" : s.join(", "));
  const rows = cat.map((m) => `| \`${m.name}\` | ${m.type} | ${m.labels.length ? m.labels.map((l) => `\`${l}\``).join(", ") : "-"} | ${all(m.services)} | ${m.help.replace(/\|/g, "\\|")} |`);
  return ["| Metric | Type | Labels | Services | Meaning |", "|---|---|---|---|---|", ...rows].join("\n");
}

export function docTable(md) {
  const a = md.indexOf(TABLE_START), b = md.indexOf(TABLE_END);
  if (a < 0 || b < 0) return null;
  return md.slice(a + TABLE_START.length, b).trim();
}

const PROMQL_WORDS = new Set(["sum", "avg", "min", "max", "count", "rate", "irate", "increase", "by", "without", "on", "ignoring", "group_left", "group_right", "and", "or", "unless", "bool", "histogram_quantile", "clamp_min", "clamp_max", "abs", "deriv", "delta", "absent", "time", "vector", "scalar", "topk", "bottomk", "quantile", "avg_over_time", "max_over_time", "min_over_time", "sum_over_time", "count_over_time", "humanizeDuration", "labels", "value", "label_replace", "up"]);

/** Parse a rules file into [{ group, kind, name, expr }]. */
export function loadRules(file) {
  const doc = parse(readFileSync(file, "utf8"));
  const out = [];
  for (const g of doc.groups ?? []) for (const r of g.rules ?? []) out.push({ group: g.name, kind: r.alert ? "alert" : "record", name: r.alert ?? r.record, expr: String(r.expr), raw: r });
  return out;
}

/** Problems found in the rules: unknown metrics, unknown labels in selectors, missing alert fields. Empty array = consistent. */
export function checkRules(rules, cat, extraMetricNames = []) {
  const problems = [];
  const byName = new Map(cat.map((m) => [m.name, m]));
  const defaults = new Set(extraMetricNames);
  const recorded = new Set(rules.filter((r) => r.kind === "record").map((r) => r.name));
  const base = (n) => (byName.has(n) ? n : n.replace(/_(bucket|sum|count)$/, ""));
  for (const r of rules) {
    if (r.kind === "alert") {
      for (const f of ["severity", "route", "slo"]) if (!r.raw.labels?.[f]) problems.push(`${r.name}: missing label ${f}`);
      if (!r.raw.annotations?.summary) problems.push(`${r.name}: missing summary annotation`);
      if (!r.raw.annotations?.runbook) problems.push(`${r.name}: missing runbook annotation`);
    }
    // 1. label names used in selectors
    for (const m of r.expr.matchAll(/([A-Za-z_:][A-Za-z0-9_:]*)\{([^}]*)\}/g)) {
      const metric = base(m[1]);
      const def = byName.get(metric);
      if (recorded.has(m[1]) || (!def && defaults.has(metric)) || m[1] === "up") continue;
      if (!def) { problems.push(`${r.name}: unknown metric ${m[1]}`); continue; }
      const allowed = new Set([...def.labels, "service", "le", "job", "instance"]);
      for (const l of m[2].matchAll(/([A-Za-z_][A-Za-z0-9_]*)\s*(?:=~|!~|!=|=)/g)) if (!allowed.has(l[1])) problems.push(`${r.name}: metric ${metric} has no label ${l[1]} (has: ${[...allowed].join(", ")})`);
    }
    // 2. every remaining identifier must be a PromQL word, a recorded series, a default metric or a catalogue metric
    const stripped = r.expr.replace(/"[^"]*"/g, '""').replace(/\{[^}]*\}/g, "").replace(/\[[^\]]*\]/g, "").replace(/\b(by|without|on|ignoring)\s*\([^)]*\)/g, "$1").replace(/\b(group_left|group_right)\s*(\([^)]*\))?/g, "");
    for (const t of stripped.matchAll(/[A-Za-z_:][A-Za-z0-9_:]*/g)) {
      const id = t[0];
      if (PROMQL_WORDS.has(id) || recorded.has(id) || defaults.has(id) || byName.has(base(id))) continue;
      problems.push(`${r.name}: unknown identifier ${id} in expression`);
    }
  }
  return problems;
}
